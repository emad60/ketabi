# جلب جميع الفصول الدراسية
terms = Term.objects.all().order_by('number')
print(f"✅ عدد الفصول الدراسية: {terms.count()}")

created_count = 0
skipped_count = 0
errors = []

# المرور على كل صف ومواده
for grade_name, subject_names in grade_subjects_mapping.items():
    try:
        grade = Grade.objects.get(name=grade_name)
        print(f"\n📚 الصف: {grade_name}")
        
        # لكل مادة في هذا الصف
        for subject_name in subject_names:
            try:
                subject = Subject.objects.get(name=subject_name)
                
                # إنشاء كتاب لكل فصل دراسي (الأول والثاني)
                for term in terms:
                    book, created = Book.objects.get_or_create(
                        subject=subject,
                        grade=grade,
                        term=term,
                        defaults={
                            'edition': '2025',
                            'year': 2025,
                            'total_quantity': 0
                        }
                    )
                    
                    if created:
                        created_count += 1
                        print(f"  ✅ {subject_name} - {term.name}")
                    else:
                        skipped_count += 1
                        
            except Subject.DoesNotExist:
                error_msg = f"المادة '{subject_name}' غير موجودة"
                errors.append(error_msg)
                print(f"  ❌ {error_msg}")
                
    except Grade.DoesNotExist:
        error_msg = f"الصف '{grade_name}' غير موجود"
        errors.append(error_msg)
        print(f"❌ {error_msg}")

print("\n" + "="*60)
print(f"✅ تم إنشاء {created_count} كتاب جديد")
print(f"⏭️  تم تخطي {skipped_count} كتاب (موجود مسبقاً)")

if errors:
    print(f"\n⚠️  عدد الأخطاء: {len(errors)}")
    for error in errors[:5]:  # عرض أول 5 أخطاء فقط
        print(f"   - {error}")
else:
    print("\n🎉 تمت العملية بنجاح بدون أخطاء!")

